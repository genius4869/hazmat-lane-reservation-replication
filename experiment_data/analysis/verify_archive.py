"""Verify the published reference files and their case identifiers without a solver."""
import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

DATA = Path(__file__).resolve().parents[1]


def records(relative):
    with (DATA / relative).open(encoding="utf-8-sig", newline="") as stream:
        if relative.endswith(".json"):
            return json.load(stream)
        return list(csv.DictReader(stream))


def require(condition, detail):
    if not condition:
        raise ValueError(detail)


def verify_files(manifest, folder, path_key, hash_key):
    for row in manifest:
        path = folder / row[path_key]
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        require(digest == row[hash_key], f"Checksum mismatch for {path.name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables", type=Path, help="Check tables and runtime summaries regenerated by build_tables.py")
    args = parser.parse_args()
    verify_files(records("sources/source_checksums.csv"), DATA / "sources", "file", "sha256")
    inputs = records("instances/inputs_manifest.csv")
    catalog = {r["case_id"]: r["input_sha256"] for r in inputs}
    require(len(inputs) == len(catalog) == 380, "Published input count")
    verify_files(inputs, DATA / "instances", "input_file", "input_sha256")
    results = records("results/checksums.csv")
    actual = {p.relative_to(DATA / "results").as_posix() for p in (DATA / "results").glob("module*/*") if p.is_file()}
    require(actual == {r["file"] for r in results}, "Published result inventory")
    verify_files(results, DATA / "results", "file", "sha256")
    scopes = [(1, "runs", 108), (2, "per_case", 31), (3, "designs", 352),
              (4, "per_case", 54), (5, "per_case", 230), (6, "per_case", 96),
              (7, "per_case", 9), (8, "per_case_roads", 46)]
    for module, name, expected in scopes:
        rows = records(f"results/module{module}/{name}.json")
        require(len(rows) == expected, f"Module {module} record count")
        for row in rows:
            case = row["case_id"]
            require(case in catalog, f"Unknown input: {case}")
            if row.get("input_sha256"):
                require(catalog[case] == row["input_sha256"], f"Wrong input binding: {case}")
    runs = records("results/module1/runs.json")
    require(len({(r["case_id"], r["algorithm"]) for r in runs}) == 108 and
            Counter(r["algorithm"] for r in runs) == {"CPA": 54, "BPA": 54}, "EM algorithm pairs")
    for case in {r["case_id"] for r in runs}:
        pair = [r for r in runs if r["case_id"] == case]
        require(max(r["verified_UB"] for r in pair) - min(r["valid_LB"] for r in pair) < 1e-4, case)
    random = records("results/module5/per_case.json")
    random_runs = records("results/module5/runs.json")
    require(len(random_runs) == 460 and
            {(r["case_id"], r["algorithm"]) for r in random_runs} ==
            {(r["case_id"], alg) for r in random for alg in ("CPA", "BPA")}, "Random algorithm pairs")
    omitted = {r["case_id"] for r in random if not r["both_certified"]}
    outcomes = records("results/module5/memory_outcomes.json")
    require(len(omitted) == 20 and {(r["case_id"], r["algorithm"]) for r in outcomes} ==
            {(case, alg) for case in omitted for alg in ("CPA", "BPA")}, "Random runtime denominator")
    if args.tables:
        expected = records("results/release_verification.json")["rebuilt_table_sha256_utf8_lf"]
        for name, digest in expected.items():
            actual = (args.tables / name).read_text(encoding="utf-8").encode("utf-8")
            require(hashlib.sha256(actual).hexdigest() == digest, f"Rebuilt table differs: {name}")
        print("Tables 1-4 and runtime summaries match the release at the paper's display precision.")
    print(f"Verified {len(catalog)} input hashes and {len(results)} reference result files for Modules 1-8.")


if __name__ == "__main__":
    main()
